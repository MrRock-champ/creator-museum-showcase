// ========================================
// RANKING ENGINE
// ========================================

export function calculateRanking(data) {
    const maxFollowers = Math.max(...data.map(c => c.followers), 1);
    const maxInteractions = Math.max(...data.map(c => c.interactions), 1);
    const maxEngagement = Math.max(...data.map(c => c.engagement), 1);
    const maxRecency = Math.max(...data.map(c => c.recency), 1);

    return data.map(creator => ({
        ...creator,
        score: Math.round(
            (creator.followers / maxFollowers) * 30 +
            (creator.interactions / maxInteractions) * 40 +
            (creator.engagement / maxEngagement) * 20 +
            (creator.recency / maxRecency) * 10
        )
    })).sort((a, b) => b.score - a.score);
}

// ========================================
// NUMBER FORMATTER
// ========================================

export function formatNumber(number) {
    if (number >= 1000000)
        return (number / 1000000).toFixed(1) + "M";

    if (number >= 1000)
        return (number / 1000).toFixed(1) + "K";

    return String(number);
}

// ========================================
// RANKING DISPLAY
// ========================================

export function renderRanking(data, onSelect) {
    const list = document.getElementById("rankingList");
    list.innerHTML = "";

    data.forEach((creator, index) => {
        const item = document.createElement("div");
        item.className = "ranking-item";
        item.setAttribute("role", "button");
        item.tabIndex = 0;
        item.setAttribute("aria-label", `Rank ${index + 1}: ${creator.username}, score ${creator.score}`);

        const avatar = document.createElement("img");
        avatar.className = "rank-avatar";
        avatar.src = creator.avatar;
        avatar.alt = creator.username;

        item.innerHTML = `
            <span class="rank-number">
                ${String(index + 1).padStart(2, "0")}
            </span>
        `;

        item.appendChild(avatar);

        const name = document.createElement("span");
        name.className = "rank-name";
        name.textContent = creator.username;

        const score = document.createElement("span");
        score.className = "rank-score";
        score.textContent = creator.score;

        item.append(name, score);
        item.addEventListener("click", () => onSelect(creator));
        item.addEventListener("keydown", event => {
            if (event.key === "Enter" || event.key === " ") {
                event.preventDefault();
                onSelect(creator);
            }
        });

        list.appendChild(item);
    });

    document.getElementById("creatorCount").textContent =
        String(data.length).padStart(2, "0");
}
